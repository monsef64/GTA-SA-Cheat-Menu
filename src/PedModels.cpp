const PedModel* GetPedModels() {
    return kPedModels;
}

int GetPedModelCount() {
    return static_cast<int>(sizeof(kPedModels) / sizeof(kPedModels[0]));
}

const PedModel* FindPedModel(uint16_t id) {
    for (const PedModel& model : kPedModels) {
        if (model.id == id) return &model;
    }
    return nullptr;
}

std::string PedModelName(uint16_t id) {
    const PedModel* model = FindPedModel(id);
    return model ? std::string(model->name) : std::string("Unknown");
}

